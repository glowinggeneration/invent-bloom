export function PlatformIcon({
  platform,
  className = "h-3.5 w-3.5",
  colored = true,
}: {
  platform: string;
  className?: string;
  colored?: boolean;
}) {
  const color = PLATFORM_COLORS[platform as KnownPlatform] ?? "currentColor";
  return (
    <svg
      viewBox="0 0 24 24"
      role="img"
      aria-label={platformLabel(platform)}
      className={className}
      style={colored ? { color } : undefined}
    >
      <Glyph platform={platform} />
    </svg>
  );
}

